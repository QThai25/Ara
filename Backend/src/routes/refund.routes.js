import { Router } from "express";
import { auth } from "../middlewares/auth.middleware.js";
import { adminOnly } from "../middlewares/admin.middleware.js";
import * as c from "../controllers/refund.controller.js";
import { validate } from "../middlewares/validate.middleware.js";
import { manualRefundContext, manualRefundCreate, manualRefundSearch, orderRefundDestination, refundComplete, refundContact, refundDestinationInput, refundId, refundOverride, refundReason } from "../validations/refund.validation.js";
import { optionalPaymentAuth } from "../middlewares/paymentAccess.middleware.js";
import { uploadRefundProofImage } from "../middlewares/upload.middleware.js";
export const refundRoutes = Router();
export const adminRefundRoutes = Router();
export const adminRefundTransactionRoutes = Router();
refundRoutes.patch("/:orderId/destination-input", ...optionalPaymentAuth, refundDestinationInput, validate, c.destinationInput);
refundRoutes.use(auth);
refundRoutes.get("/:orderId", c.getOrder);
refundRoutes.patch("/:orderId/destination", orderRefundDestination, validate, c.destination);
adminRefundRoutes.use(auth, adminOnly);
adminRefundRoutes.get("/", c.list);
adminRefundRoutes.get("/:id", refundId, validate, c.detail);
adminRefundRoutes.patch("/:id/start", refundId, validate, c.start);
adminRefundRoutes.post("/:id/request-information", refundId, validate, c.requestInformation);
adminRefundRoutes.patch("/:id/contact", refundContact, validate, c.contact);
adminRefundRoutes.post("/:id/proofs", refundId, validate, uploadRefundProofImage.single("image"), c.uploadProof);
adminRefundRoutes.patch("/:id/complete", refundComplete, validate, c.complete);
adminRefundRoutes.patch("/:id/fail", refundReason, validate, c.fail);
adminRefundRoutes.patch("/:id/cancel", refundReason, validate, c.cancel);
adminRefundRoutes.patch("/:id/retry", refundId, validate, c.retry);
adminRefundRoutes.patch("/:id/destination-override", refundOverride, validate, c.overrideDestination);

adminRefundTransactionRoutes.use(auth, adminOnly);
adminRefundTransactionRoutes.get("/search", manualRefundSearch, validate, c.manualSearch);
adminRefundTransactionRoutes.get("/context", manualRefundContext, validate, c.manualContext);
adminRefundTransactionRoutes.get("/", c.manualList);
adminRefundTransactionRoutes.post("/", manualRefundCreate, validate, c.manualCreate);
adminRefundTransactionRoutes.get("/:id", refundId, validate, c.manualDetail);
adminRefundTransactionRoutes.patch("/:id/start", refundId, validate, c.start);
adminRefundTransactionRoutes.post("/:id/request-information", refundId, validate, c.requestInformation);
adminRefundTransactionRoutes.patch("/:id/contact", refundContact, validate, c.contact);
adminRefundTransactionRoutes.post("/:id/proofs", refundId, validate, uploadRefundProofImage.single("image"), c.uploadProof);
adminRefundTransactionRoutes.patch("/:id/complete", refundComplete, validate, c.complete);
adminRefundTransactionRoutes.patch("/:id/fail", refundReason, validate, c.fail);
adminRefundTransactionRoutes.patch("/:id/cancel", refundReason, validate, c.cancel);
adminRefundTransactionRoutes.patch("/:id/retry", refundId, validate, c.retry);
adminRefundTransactionRoutes.patch("/:id/destination-override", refundOverride, validate, c.overrideDestination);
